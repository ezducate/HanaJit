def _run_if_linked(out, *args):
    if out.executable is None:
        return None
    r = subprocess.run([out.executable, *map(str, args)],
                       capture_output=True, text=True, timeout=20)
    assert r.returncode == 0, r.stderr
    return r.stdout.strip()


def test_scalar_executable_artifacts_and_execution(tmp_path):
    @jit(signature="i64, i64")
    def add_mul(a, b):
        return a * 3 + b

    out = add_mul.export_executable(tmp_path / "add_mul")
    assert Path(out.object).is_file()
    assert Path(out.object).stat().st_size > 0
    assert Path(out.source).is_file()
    assert Path(out.build).is_file()
    assert out.ptx is None
    source = Path(out.source).read_text(encoding="utf-8")
    assert "static int64_t hj_cpu_kernel(int64_t hj_v0, int64_t hj_v1)" in source
    assert "strtoll" in source
    assert "Python.h" not in source
    assert "hanajit" not in source.lower().replace(
        "generated by hanajit.export_executable", "")
    got = _run_if_linked(out, 7, -2)
    if got is not None:
        assert got == "19"


