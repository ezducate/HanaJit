def test_output_path_with_spaces_and_build_script_rebuild(tmp_path):
    @jit(signature="i64")
    def double(x):
        return x * 2

    out = double.export_executable(tmp_path / "directory with spaces" /
                                   "double tool")
    got = _run_if_linked(out, 21)
    if got is None:
        return
    assert got == "42"
    if os.name == "nt":
        command = ["cmd.exe", "/d", "/c", out.build]
    else:
        command = ["/bin/sh", out.build]
    rebuilt = subprocess.run(command, capture_output=True, text=True,
                             timeout=120)
    assert rebuilt.returncode == 0, rebuilt.stderr or rebuilt.stdout
    assert _run_if_linked(out, 8) == "16"


def test_cpu_executable_runs_without_python_environment(tmp_path):
    @jit(signature="i64")
    def increment(x):
        return x + 1

    out = increment.export_executable(tmp_path / "empty_env")
    if out.executable is None:
        return
    env = {}
    if os.name == "nt":
        # CPython 3.10 cannot pass a completely empty environment block to
        # CreateProcess.  SystemRoot is enough for Windows while still
        # proving that the executable needs no Python/HanaJit environment.
        env["SystemRoot"] = os.environ["SystemRoot"]
    r = subprocess.run([out.executable, "41"], capture_output=True,
                       text=True, timeout=20, env=env)
    assert r.returncode == 0, r.stderr
    assert r.stdout.strip() == "42"


