def test_executable_loops_control_flow_and_recursion(tmp_path):
    @jit(signature="i64")
    def loop(n):
        acc = 0
        for i in range(-3, n, 2):
            if i % 5 == 0:
                continue
            acc += i * i
        return acc

    @jit(signature="i64")
    def fib(n):
        if n < 2:
            return n
        return fib(n - 1) + fib(n - 2)

    loop_out = loop.export_executable(tmp_path / "loop")
    fib_out = fib.export_executable(tmp_path / "fib")
    got = _run_if_linked(loop_out, 31)
    if got is not None:
        assert int(got) == loop.__wrapped__(31)
    got = _run_if_linked(fib_out, 20)
    if got is not None:
        assert int(got) == 6765


