def test_integer_bitwise_shift_and_unary_semantics(tmp_path):
    @jit(signature="i64, i64")
    def integer_ops(a, b):
        mixed = (a & b) ^ (a | b)
        shifted = (a << 3) + (b >> 2)
        return +mixed - shifted + abs(-b)

    out = integer_ops.export_executable(tmp_path / "integer_ops")
    for a, b in ((23, 9), (-23, 9), (123456, -311)):
        got = _run_if_linked(out, a, b)
        if got is not None:
            assert int(got) == integer_ops.__wrapped__(a, b)


